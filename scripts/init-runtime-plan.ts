import { readFile } from "node:fs/promises";
import { join } from "node:path";
import type { SetupCommandOptions } from "./runtime-setup-command-options.js";
import {
  buildModelConfig,
  buildProviderConfig,
  DEFAULT_ROOT_RESPONSE_METHODOLOGY_FILES,
  isRecord,
  type JsonObject,
  type Provider,
} from "./runtime-setup-files.js";

export type InitFilePlan = Readonly<{
  relativePath: string;
  content: string;
  status: "created" | "overwritten" | "kept";
  envLineChanged?: boolean;
}>;

type InitPlanOptions = SetupCommandOptions & {
  rootDir: string;
  provider: Provider;
  model: string;
  baseUrl?: string;
  force: boolean;
};

function configureRuntimeProvider(
  config: JsonObject,
  options: InitPlanOptions,
): JsonObject {
  const models = isRecord(config.models) ? config.models : {};
  const { defaults: _ignoredDefaults, ...modelSettings } = models;
  return {
    ...config,
    models: {
      ...modelSettings,
      providers: {
        [options.provider]: buildProviderConfig(
          options.provider,
          options.baseUrl,
          options.apiKeyEnv,
        ),
      },
      profiles: { default: { configRef: "./models/default.config.json" } },
    },
  };
}

function configureRunner(config: JsonObject): JsonObject {
  const models = isRecord(config.models) ? config.models : {};
  const defaults = isRecord(models.defaults) ? models.defaults : {};
  return {
    ...config,
    models: { ...models, defaults: { ...defaults, profileId: "default" } },
  };
}

function ensureEnvConfigPointer(raw: string): string {
  const hasConfigLine = raw
    .split(/\r?\n/)
    .some((line) => line.trim().startsWith("LLM_RUNTIME_CONFIG_FILE="));
  const terminated = raw.endsWith("\n") ? raw : `${raw}\n`;
  if (hasConfigLine) return terminated;
  return `${terminated}LLM_RUNTIME_CONFIG_FILE=local/runtime.config.json\n`;
}

async function readExistingInitFile(path: string): Promise<string | undefined> {
  try {
    return await readFile(path, "utf-8");
  } catch (error) {
    if (isRecord(error) && error.code === "ENOENT") return undefined;
    throw error;
  }
}

function initFileStatus(
  existing: string | undefined,
  force: boolean,
): InitFilePlan["status"] {
  if (existing === undefined) return "created";
  if (force) return "overwritten";
  return "kept";
}

/** Plan the exact preserved or generated bytes before writing any active files. */
export async function planInitRuntimeFiles(
  options: InitPlanOptions,
  templateRoot: string,
): Promise<InitFilePlan[]> {
  const definitions = [
    { relativePath: ".env", template: "examples/env.example" },
    {
      relativePath: "local/runtime.config.json",
      template: "examples/runtime.config.example.json",
      configure: (config: JsonObject) =>
        configureRuntimeProvider(config, options),
    },
    {
      relativePath: "local/request-runner.config.json",
      template: "examples/request-runner.config.example.json",
      configure: configureRunner,
    },
    {
      relativePath: "local/models/default.config.json",
      template: "examples/models/default.config.json",
      configure: (config: JsonObject) =>
        buildModelConfig(
          config,
          options.provider,
          options.model,
          options.contextWindowTokens,
          options.modelOptions,
          options.label,
        ),
    },
    ...DEFAULT_ROOT_RESPONSE_METHODOLOGY_FILES.map((relativePath) => ({
      relativePath,
      template: relativePath,
    })),
  ];
  return Promise.all(
    definitions.map(async (definition): Promise<InitFilePlan> => {
      const existing = await readExistingInitFile(
        join(options.rootDir, definition.relativePath),
      );
      const keepExisting = existing !== undefined && !options.force;
      let content = keepExisting
        ? existing
        : await readFile(join(templateRoot, definition.template), "utf-8");
      if (!keepExisting && "configure" in definition && definition.configure) {
        content = `${JSON.stringify(definition.configure(JSON.parse(content)), null, 2)}\n`;
      }
      const envLineChanged =
        definition.relativePath === ".env" &&
        ensureEnvConfigPointer(content) !== content;
      if (envLineChanged) content = ensureEnvConfigPointer(content);
      return {
        relativePath: definition.relativePath,
        content,
        status: initFileStatus(existing, options.force),
        ...(envLineChanged ? { envLineChanged: true } : {}),
      };
    }),
  );
}
